import { writeFile } from 'node:fs/promises'
import { chromium } from '../../source/apps/web/node_modules/playwright/index.mjs'

const url = 'http://127.0.0.1:53988/'
const out = '/Users/jane/Documents/DeepSeek-Harness-Dev-Assets/Studios/S3/results'
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
const page = await context.newPage()
const evidence = { url, viewport: null, title: null, root: null, buttons: [], pageErrors: [], consoleErrors: [], requestFailures: [] }
await page.route('**/*', route => new URL(route.request().url()).origin === new URL(url).origin ? route.continue() : route.abort())
page.on('pageerror', error => evidence.pageErrors.push(error.name))
page.on('console', message => { if (message.type() === 'error') evidence.consoleErrors.push(message.text().slice(0, 300)) })
page.on('requestfailed', request => evidence.requestFailures.push(new URL(request.url()).pathname))
await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 12_000 })
await page.waitForTimeout(2_000)
evidence.viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight, dpr: devicePixelRatio }))
evidence.title = await page.title()
evidence.root = await page.evaluate(() => ({ exists: Boolean(document.querySelector('#root')), children: document.querySelector('#root')?.childElementCount ?? 0 }))
evidence.buttons = await page.getByRole('button').allTextContents()
if (await page.getByRole('button', { name: 'Continue', exact: true }).count()) {
  await page.getByRole('button', { name: 'Continue', exact: true }).evaluate(button => button.click())
  await page.waitForTimeout(500)
}
await page.screenshot({ path: `${out}/s3-client-initial.png`, fullPage: true })
const studiosButton = page.getByRole('button', { name: 'Studios', exact: true })
evidence.studiosButtonCount = await studiosButton.count()
if (await studiosButton.count()) await studiosButton.evaluate(button => button.click())
await page.waitForTimeout(1_500)
evidence.studiosHeadings = await page.getByRole('heading').allTextContents()
evidence.studiosButtons = await page.getByRole('button').allTextContents()
await page.screenshot({ path: `${out}/s3-studios-surface.png`, fullPage: true })
const configureLater = page.getByRole('button', { name: 'Configure later', exact: true })
if (await configureLater.count()) await configureLater.evaluate(button => button.click())
await page.waitForTimeout(700)
const videoStudioButton = page.getByRole('button', { name: /Video Studio/ })
evidence.videoStudioButtonCount = await videoStudioButton.count()
if (await videoStudioButton.count()) await videoStudioButton.evaluate(button => button.click())
await page.waitForTimeout(800)
evidence.videoStudioHeadings = await page.getByRole('heading').allTextContents()
evidence.videoStudioButtons = await page.getByRole('button').allTextContents()
await page.screenshot({ path: `${out}/s3-video-studio.png`, fullPage: true })
const packagingButton = page.getByRole('button', { name: /Video Packaging/ })
evidence.packagingButtonCount = await packagingButton.count()
if (await packagingButton.count()) await packagingButton.evaluate(button => button.click())
await page.waitForTimeout(800)
evidence.packagingHeadings = await page.getByRole('heading').allTextContents()
evidence.packagingIframes = await page.locator('iframe').count()
evidence.packagingButtons = await page.getByRole('button').allTextContents()
await page.screenshot({ path: `${out}/s3-video-packaging.png`, fullPage: true })
await writeFile(`${out}/client-smoke.json`, `${JSON.stringify(evidence, null, 2)}\n`)
console.log(JSON.stringify(evidence))
await browser.close()
